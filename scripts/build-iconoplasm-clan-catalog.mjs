// Builds the static Iconoplasm clan catalog consumed by the stateful worker's
// /api/iconoplasm/clans endpoint.
//
// Why a committed bundle instead of a live D1 scan: the clan -> aesthetic mapping
// is deterministic reference data owned by the authoring control plane. Bundling
// it means the Clans backend costs nothing beyond the per-user discovery read it
// already needs: no whole-inventory D1/KV scan on a public path.
//
// Source of truth:
//   D:/Coding/Datasets/iconoplasm/mapping.json
//   D:/Coding/Datasets/iconoplasm/clan_accession_map.json

import { readFileSync, writeFileSync, mkdirSync } from "node:fs"
import { dirname, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const here = dirname(fileURLToPath(import.meta.url))
const datasetsRoot = process.env.ICONOPLASM_DATASETS_ROOT || "D:/Coding/Datasets/iconoplasm"
const outPath = resolve(here, "../workers/generated/iconoplasm-clan-catalog.js")

function readJson(relPath) {
  return JSON.parse(readFileSync(resolve(datasetsRoot, relPath), "utf8"))
}

function aestheticUrl(name) {
  const trimmed = String(name || "").trim()
  if (!trimmed) return null
  const slug = trimmed.split(/\s+/).map(encodeURIComponent).join("_")
  return `https://aesthetics.fandom.com/wiki/${slug}`
}

function pfamUrl(accession) {
  const acc = String(accession || "").trim()
  if (!acc) return null
  return `https://www.ebi.ac.uk/interpro/set/pfam/${encodeURIComponent(acc)}/`
}

const mapping = readJson("mapping.json")
const accessions = readJson("clan_accession_map.json")

const entries = Object.keys(mapping)
  .map((clan) => String(clan || "").trim())
  .filter(Boolean)
  .sort((a, b) => a.localeCompare(b))
  .map((clan) => {
    const aesthetic = String(mapping[clan] || "").trim()
    const accession = String(accessions[clan] || "").trim() || null
    return {
      clan,
      accession,
      aesthetic,
      aesthetic_url: aestheticUrl(aesthetic),
      pfam_url: pfamUrl(accession),
    }
  })

const banner =
  "// AUTO-GENERATED by scripts/build-iconoplasm-clan-catalog.mjs. Do not edit by hand.\n" +
  "// Source: Datasets/iconoplasm/{mapping.json, clan_accession_map.json}.\n" +
  "// Regenerate after clan/aesthetic remaps: node scripts/build-iconoplasm-clan-catalog.mjs\n"

mkdirSync(dirname(outPath), { recursive: true })
writeFileSync(
  outPath,
  `${banner}export const ICONOPLASM_CLAN_CATALOG = ${JSON.stringify(entries)}\n`,
  "utf8",
)

const withAesthetic = entries.filter((entry) => entry.aesthetic).length
const withAccession = entries.filter((entry) => entry.accession).length
console.log(
  `Wrote ${entries.length} clans (${withAesthetic} with aesthetic, ${withAccession} with Pfam accession) -> ${outPath}`,
)
