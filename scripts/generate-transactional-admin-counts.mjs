import { readFileSync, writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"
import { createHash } from "node:crypto"

// One formula per counter, shared by the initial seed and every OLD/NEW delta.
// Generated SQL is reviewed and admitted as migration 0095, never evaluated
// from a caller's text or run by the application on a cache miss.
function dashboard(prefix) {
  const column = (name, fallback = 0) =>
    prefix ? `COALESCE(${prefix}.${name}, ${fallback})` : String(fallback)
  const hasLive = `${column("current_asset_sha256", "''")} <> ''`
  const candidates = column("candidate_count")
  return {
    genes: "1",
    with_live: `(${hasLive})`,
    overrides: `(${column("admin_override")} = 1 AND ${hasLive})`,
    drift: `(${column("current_asset_missing")} = 1)`,
    current_asset_missing: `(${column("current_asset_missing")} = 1)`,
    missing: `(${candidates} = 0)`,
    no_live: `(${column("current_asset_sha256", "''")} = '')`,
    stale_assets: column("stale_count"),
    legacy_assets: column("legacy_count"),
    zero_candidates: `(${candidates} = 0)`,
    one_candidate: `(${candidates} = 1)`,
    two_to_five_candidates: `(${candidates} BETWEEN 2 AND 5)`,
    six_plus_candidates: `(${candidates} >= 6)`,
  }
}

function live(prefix) {
  if (!prefix) return { all: "0", mismatch: "0", pinned: "0", missing: "0", stale: "0" }
  return {
    all: "1",
    mismatch: `(COALESCE(${prefix}.current_asset_missing, 0) = 1)`,
    pinned: `(COALESCE(${prefix}.admin_override, 0) = 1)`,
    missing: `(COALESCE(${prefix}.candidate_count, 0) = 0)`,
    stale: `(COALESCE(${prefix}.stale_count, 0) > 0)`,
  }
}

function cacheDelta(mode, filter, delta, condition = delta) {
  return `UPDATE icono_admin_gallery_count_cache SET total = total + (${delta}), updated_at = CURRENT_TIMESTAMP WHERE count_key = '${mode}:${filter}' AND (${condition}) <> 0;`
}

function rollupDelta(before, after) {
  const symbol = `${after || before}.gene_symbol`
  const old = dashboard(before),
    next = dashboard(after)
  const previousLive = live(before),
    nextLive = live(after)
  const statements = [
    `UPDATE icono_admin_dashboard_summary SET
    ${Object.keys(next)
      .filter((key) => key !== "genes")
      .map((key) => `${key} = ${key} + (${next[key]}) - (${old[key]})`)
      .join(",\n    ")},
    updated_at = CURRENT_TIMESTAMP WHERE summary_key = 'default'
    AND EXISTS (SELECT 1 FROM icono_gene_catalog WHERE gene_symbol = ${symbol});`,
  ]
  for (const filter of Object.keys(nextLive))
    statements.push(cacheDelta("live", filter, `${nextLive[filter]} - ${previousLive[filter]}`))
  for (const filter of ["mismatch", "pinned"]) {
    statements.push(
      cacheDelta(
        "all",
        filter,
        `(${nextLive[filter]} - ${previousLive[filter]}) *
      (SELECT COUNT(*) FROM icono_portrait_assets WHERE gene_symbol = ${symbol} AND asset_sha256 <> '')`,
        `${nextLive[filter]} - ${previousLive[filter]}`,
      ),
    )
  }
  return statements.join("\n  ")
}

function catalogueDelta(prefix, sign) {
  const values = dashboard("gr")
  const keys = Object.keys(values)
  return `UPDATE icono_admin_dashboard_summary SET (${keys.join(", ")}) = (
    SELECT ${keys.map((key) => `icono_admin_dashboard_summary.${key} ${sign} (${values[key]})`).join(",\n      ")}
    FROM (SELECT 1) singleton LEFT JOIN icono_admin_gene_rollup gr ON gr.gene_symbol = ${prefix}.gene_symbol
  ), updated_at = CURRENT_TIMESTAMP WHERE summary_key = 'default';`
}

function assetDelta(prefix, sign) {
  const valid = `(COALESCE(${prefix}.asset_sha256, '') <> '')`
  const statements = [
    cacheDelta("all", "all", `${sign} ${valid}`),
    cacheDelta("all", "stale", `${sign} (${valid} AND COALESCE(${prefix}.is_stale, 0) = 1)`),
  ]
  for (const [filter, column] of [
    ["mismatch", "current_asset_missing"],
    ["pinned", "admin_override"],
  ]) {
    statements.push(
      cacheDelta(
        "all",
        filter,
        `${sign} (${valid} AND EXISTS (
      SELECT 1 FROM icono_admin_gene_rollup WHERE gene_symbol = ${prefix}.gene_symbol AND ${column} = 1))`,
      ),
    )
  }
  return statements.join("\n  ")
}

export function transactionalAdminCountMigration() {
  const columns = dashboard("gr")
  const statements = [
    "-- Generated by scripts/generate-transactional-admin-counts.mjs.",
    "-- IPD-012: exact admin counts belong to source mutations, not repeated catalogue scans.",
    "-- Preserve orphan asset totals, catalogue-only dashboard counts and all existing filters.",
    "-- The one-time seed is cost-admitted; subsequent deltas touch only changed genes/assets.",
    `INSERT OR REPLACE INTO icono_admin_dashboard_summary (summary_key, ${Object.keys(columns).join(", ")}, updated_at)
      SELECT 'default', ${Object.values(columns)
        .map((value) => `COALESCE(SUM(${value}), 0)`)
        .join(",\n        ")}, CURRENT_TIMESTAMP
      FROM icono_gene_catalog gc LEFT JOIN icono_admin_gene_rollup gr ON gr.gene_symbol = gc.gene_symbol;`,
  ]
  const seedCounts = (mode, expressions, from) => `WITH counts AS (
    SELECT ${Object.entries(expressions)
      .map(([key, value]) => `COALESCE(SUM(${value}), 0) AS count_${key}`)
      .join(",\n      ")} ${from}
    ), filters(filter) AS (VALUES ${Object.keys(expressions)
      .map((key) => `('${key}')`)
      .join(", ")})
    INSERT OR REPLACE INTO icono_admin_gallery_count_cache (count_key, mode, filter, total, updated_at)
    SELECT '${mode}:' || filter, '${mode}', filter, CASE filter ${Object.keys(expressions)
      .map((key) => `WHEN '${key}' THEN count_${key}`)
      .join(" ")} END,
      CURRENT_TIMESTAMP FROM counts CROSS JOIN filters;`
  statements.push(seedCounts("live", live("gr"), "FROM icono_admin_gene_rollup gr"))
  const all = {
    all: "1",
    mismatch: "COALESCE(gr.current_asset_missing, 0) = 1",
    pinned: "COALESCE(gr.admin_override, 0) = 1",
    missing: "0",
    stale: "COALESCE(pa.is_stale, 0) = 1",
  }
  statements.push(
    seedCounts(
      "all",
      all,
      "FROM icono_portrait_assets pa LEFT JOIN icono_admin_gene_rollup gr ON gr.gene_symbol = pa.gene_symbol WHERE pa.asset_sha256 <> ''",
    ),
  )
  const trigger = (name, operation, table, body) =>
    statements.push(`CREATE TRIGGER ${name} AFTER ${operation} ON ${table}
${
  operation.startsWith("UPDATE OF ")
    ? "WHEN " +
      operation
        .slice(10)
        .split(", ")
        .map((column) => `OLD.${column} IS NOT NEW.${column}`)
        .join(" OR ") +
      "\n"
    : ""
}BEGIN
  ${body}
END;`)
  trigger(
    "trg_icono_admin_counts_rollup_insert",
    "INSERT",
    "icono_admin_gene_rollup",
    rollupDelta(null, "NEW"),
  )
  trigger(
    "trg_icono_admin_counts_rollup_delete",
    "DELETE",
    "icono_admin_gene_rollup",
    rollupDelta("OLD", null),
  )
  trigger(
    "trg_icono_admin_counts_rollup_update",
    "UPDATE OF gene_symbol, current_asset_sha256, current_asset_missing, admin_override, candidate_count, stale_count, legacy_count",
    "icono_admin_gene_rollup",
    `${rollupDelta("OLD", null)}\n  ${rollupDelta(null, "NEW")}`,
  )
  trigger(
    "trg_icono_admin_counts_catalog_insert",
    "INSERT",
    "icono_gene_catalog",
    catalogueDelta("NEW", "+"),
  )
  trigger(
    "trg_icono_admin_counts_catalog_delete",
    "DELETE",
    "icono_gene_catalog",
    catalogueDelta("OLD", "-"),
  )
  trigger(
    "trg_icono_admin_counts_catalog_update",
    "UPDATE OF gene_symbol",
    "icono_gene_catalog",
    `${catalogueDelta("OLD", "-")}\n  ${catalogueDelta("NEW", "+")}`,
  )
  trigger(
    "trg_icono_admin_counts_asset_insert",
    "INSERT",
    "icono_portrait_assets",
    assetDelta("NEW", "+"),
  )
  trigger(
    "trg_icono_admin_counts_asset_delete",
    "DELETE",
    "icono_portrait_assets",
    assetDelta("OLD", "-"),
  )
  trigger(
    "trg_icono_admin_counts_asset_update",
    "UPDATE OF gene_symbol, asset_sha256, is_stale",
    "icono_portrait_assets",
    `${assetDelta("OLD", "-")}\n  ${assetDelta("NEW", "+")}`,
  )
  return statements.join("\n\n") + "\n"
}

// Production seeds may exceed a single release's remaining allowance. Store
// only aggregate totals and a SQLite rowid cursor, never copied source rows.
// The caller must keep application mutations paused until triggers are installed.
export function transactionalAdminCountSeedPhases() {
  const size = 1024
  const totals = {
    ...Object.fromEntries(Object.keys(dashboard("gr")).map((key) => [`d_${key}`, 0])),
    ...Object.fromEntries(Object.keys(live("gr")).map((key) => [`l_${key}`, 0])),
    ...Object.fromEntries(Object.keys(live("gr")).map((key) => [`a_${key}`, 0])),
  }
  const progress = "icono_admin_counts_seed_progress"
  const initialize = [
    `CREATE TABLE IF NOT EXISTS ${progress} (id INTEGER PRIMARY KEY CHECK(id=1), phase TEXT NOT NULL, cursor INTEGER, seed_identity TEXT NOT NULL, ${Object.keys(
      totals,
    )
      .map((key) => `${key} INTEGER NOT NULL DEFAULT 0`)
      .join(", ")})`,
    `INSERT OR IGNORE INTO ${progress}(id,phase,seed_identity) VALUES(1,'catalog','SEED_IDENTITY')`,
  ]
  const freezeTriggers = []
  for (const table of ["icono_gene_catalog", "icono_admin_gene_rollup", "icono_portrait_assets"])
    for (const action of ["INSERT", "UPDATE", "DELETE"]) {
      const name = `trg_icono_admin_seed_freeze_${table}_${action.toLowerCase()}`
      freezeTriggers.push(name)
      initialize.push(`CREATE TRIGGER IF NOT EXISTS ${name} BEFORE ${action} ON ${table}
        WHEN COALESCE((SELECT phase FROM ${progress} WHERE id=1),'incomplete') <> 'complete'
        BEGIN SELECT RAISE(ABORT,'COST_ADMIN_SEED_IN_PROGRESS'); END`)
    }
  const pages = {}
  const specs = [
    [
      "catalog",
      "rollup",
      "icono_gene_catalog",
      "gene_symbol",
      "d",
      dashboard("gr"),
      "LEFT JOIN icono_admin_gene_rollup gr ON gr.gene_symbol=p.gene_symbol",
    ],
    [
      "rollup",
      "assets",
      "icono_admin_gene_rollup",
      "current_asset_missing,admin_override,candidate_count,stale_count",
      "l",
      live("p"),
      "",
    ],
    [
      "assets",
      "finish",
      "icono_portrait_assets",
      "gene_symbol,asset_sha256,is_stale",
      "a",
      {
        all: "(p.asset_sha256 <> '')",
        mismatch: "(p.asset_sha256 <> '' AND COALESCE(gr.current_asset_missing,0)=1)",
        pinned: "(p.asset_sha256 <> '' AND COALESCE(gr.admin_override,0)=1)",
        missing: "0",
        stale: "(p.asset_sha256 <> '' AND COALESCE(p.is_stale,0)=1)",
      },
      "LEFT JOIN icono_admin_gene_rollup gr ON gr.gene_symbol=p.gene_symbol",
    ],
  ]
  for (const [phase, next, table, columns, prefix, values, join] of specs) {
    const names = Object.keys(values).map((key) => `${prefix}_${key}`)
    pages[phase] = `WITH page AS MATERIALIZED (
      SELECT rowid AS source_rowid,${columns} FROM ${table}
      WHERE rowid >= COALESCE((SELECT cursor FROM ${progress} WHERE id=1),-9223372036854775808)
      ORDER BY rowid LIMIT ${size}
    ) UPDATE ${progress} SET (${names.join(", ")},cursor,phase) = (
      SELECT ${Object.entries(values)
        .map(([key, value]) => `${prefix}_${key}+COALESCE(SUM(${value}),0)`)
        .join(", ")},
      CASE WHEN COUNT(*) < ${size} THEN NULL ELSE MAX(p.source_rowid)+1 END,
      CASE WHEN COUNT(*) < ${size} THEN '${next}' ELSE '${phase}' END
      FROM page p ${join}
    ) WHERE id=1 AND phase='${phase}'`
  }
  const finish = [
    ...freezeTriggers.map((name) => `DROP TRIGGER ${name}`),
    `INSERT OR REPLACE INTO icono_admin_dashboard_summary(summary_key,${Object.keys(dashboard("gr")).join(",")},updated_at)
      SELECT 'default',${Object.keys(dashboard("gr"))
        .map((key) => `d_${key}`)
        .join(",")},CURRENT_TIMESTAMP FROM ${progress} WHERE id=1 AND phase='finish'`,
    ...["live", "all"].flatMap((mode) =>
      Object.keys(live("gr")).map(
        (filter) =>
          `INSERT OR REPLACE INTO icono_admin_gallery_count_cache(count_key,mode,filter,total,updated_at)
       SELECT '${mode}:${filter}','${mode}','${filter}',${mode === "live" ? "l" : "a"}_${filter},CURRENT_TIMESTAMP FROM ${progress} WHERE id=1 AND phase='finish'`,
      ),
    ),
  ]
  const identity = createHash("sha256")
    .update(JSON.stringify({ initialize, pages, finish }))
    .digest("hex")
  return {
    size,
    identity,
    initialize: initialize.map((sql) => sql.replace("SEED_IDENTITY", identity)),
    pages,
    finish,
    status: `SELECT phase FROM ${progress} WHERE id=1`,
    complete: `DROP TABLE ${progress}`,
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const target = new URL(
    "../migrations-iconoplasm/0095_transactional_admin_counts.sql",
    import.meta.url,
  )
  const source = transactionalAdminCountMigration()
  if (process.argv.includes("--check")) {
    if (readFileSync(target, "utf8").replace(/\r\n/g, "\n") !== source)
      throw new Error("Admin count migration is stale")
  } else writeFileSync(target, source, "utf8")
}
