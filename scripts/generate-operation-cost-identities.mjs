import { createHash } from "node:crypto"
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"
import path from "node:path"
import { buildSync } from "esbuild"

const root = fileURLToPath(new URL("../", import.meta.url))
function costAuthoritySources(sourceRoot) {
  // esbuild already resolves the actual imported source graph. Cost receipts
  // should change when an adapter or its helper changes, not when unrelated
  // website copy changes in another Worker module.
  const result = buildSync({
    absWorkingDir: sourceRoot,
    entryPoints: ["workers/iconoplasm/operation-cost-http.js"],
    bundle: true,
    packages: "external",
    platform: "neutral",
    format: "esm",
    write: false,
    metafile: true,
    logLevel: "silent",
  })
  const inputs = Object.values(result.metafile.inputs)
  return {
    files: Object.keys(result.metafile.inputs).filter(
      (name) => name !== "workers/generated/operation-cost-identities.js",
    ),
    packages: [
      ...new Set(
        inputs.flatMap((input) =>
          input.imports.filter((entry) => entry.external).map((entry) => entry.path),
        ),
      ),
    ],
  }
}

// B-863: the exact version of each npm package the cost code imports, not the
// whole lockfile. A dev-only tool (a browser test, a linter) never reaches the
// Worker, so it must not change the executable identity. Today the graph
// imports no packages at all.
function packageVersions(sourceRoot, specifiers) {
  return specifiers
    .map((specifier) => {
      const name = specifier.startsWith("@")
        ? specifier.split("/").slice(0, 2).join("/")
        : specifier.split("/")[0]
      if (name.startsWith("node:") || name.startsWith("cloudflare:")) return name
      const manifest = JSON.parse(
        readFileSync(path.join(sourceRoot, "node_modules", name, "package.json"), "utf8"),
      )
      return `${name}@${manifest.version}`
    })
    .sort()
}

// The migration schema remains an independent identity.
const schemaDirectories = [
  "migrations",
  "workers/benchmark/migrations",
  "migrations-iconoplasm",
  "migrations-iconoplasm-authoring",
]

function digest(sourceRoot, files, extra = "") {
  const hash = createHash("sha256")
  if (extra) hash.update(extra + "\n")
  for (const name of [...files].sort()) {
    hash.update(name + "\n")
    hash.update(readFileSync(path.join(sourceRoot, name), "utf8").replace(/\r\n/g, "\n"))
    hash.update("\n")
  }
  return hash.digest("hex")
}

export function operationCostIdentities({ sourceRoot = root } = {}) {
  const graph = costAuthoritySources(sourceRoot)
  const sourceFiles = [
    ...graph.files,
    "wrangler.the-only-allowed-internal-stateful-worker-do-not-duplicate.toml",
    "scripts/generate-operation-cost-migrations.mjs",
  ]
  return {
    executable_sha256: digest(
      sourceRoot,
      sourceFiles,
      packageVersions(sourceRoot, graph.packages).join("\n"),
    ),
    schema_sha256: digest(
      sourceRoot,
      schemaDirectories.flatMap((directory) =>
        readdirSync(path.join(sourceRoot, directory))
          .filter((name) => name.endsWith(".sql"))
          .map((name) => `${directory}/${name}`),
      ),
    ),
  }
}

function generatedOutput() {
  return `// Generated by scripts/generate-operation-cost-identities.mjs. Not committed (B-863):\n// the test runner, CI and the deploy regenerate it from the sources.\n// Plans bind to the deployed query implementation and complete migration set.\nexport const OPERATION_COST_IDENTITIES = Object.freeze(${JSON.stringify(operationCostIdentities(), null, 2)})\n`
}
const target = path.join(root, "workers/generated/operation-cost-identities.js")
export function assertOperationCostIdentitiesCurrent() {
  const expected = generatedOutput()
  if (readFileSync(target, "utf8").replace(/\r\n/g, "\n") !== expected) {
    throw new Error(
      "Operation cost identities are stale; regenerate before release. Expected output:\n" +
        expected,
    )
  }
}
export function writeOperationCostIdentities() {
  mkdirSync(path.dirname(target), { recursive: true })
  writeFileSync(target, generatedOutput(), "utf8")
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeOperationCostIdentities()
}
