import { createHash } from "node:crypto"
import { readFileSync, readdirSync, writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"
import path from "node:path"

const root = fileURLToPath(new URL("../", import.meta.url))
function runtimeSources(directory) {
  return readdirSync(path.join(root, directory), { withFileTypes: true }).flatMap((entry) => {
    const name = `${directory}/${entry.name}`
    if (entry.isDirectory()) return runtimeSources(name)
    return /\.(?:[cm]?js|json)$/.test(name) &&
      !/\.(?:test|spec)\.[cm]?js$/.test(name) &&
      name !== "workers/generated/operation-cost-identities.js" &&
      !name.startsWith("workers/generated/iconoplasm-observability-snapshot.")
      ? [name]
      : []
  })
}

// Cover imported domain handlers as well as the gate itself. A hand-maintained
// short list allowed a changed transitive SQL helper to keep old plans valid.
const sourceFiles = [
  ...runtimeSources("workers"),
  ...runtimeSources("shared"),
  "pnpm-lock.yaml",
  "wrangler.the-only-allowed-internal-stateful-worker-do-not-duplicate.toml",
  "scripts/generate-operation-cost-migrations.mjs",
]
const schemaDirectories = ["migrations", "migrations-iconoplasm", "migrations-iconoplasm-authoring"]

function digest(files) {
  const hash = createHash("sha256")
  for (const name of [...files].sort()) {
    hash.update(name + "\n")
    hash.update(readFileSync(path.join(root, name), "utf8").replace(/\r\n/g, "\n"))
    hash.update("\n")
  }
  return hash.digest("hex")
}

export function operationCostIdentities() {
  return {
    executable_sha256: digest(sourceFiles),
    schema_sha256: digest(
      schemaDirectories.flatMap((directory) =>
        readdirSync(path.join(root, directory))
          .filter((name) => name.endsWith(".sql"))
          .map((name) => `${directory}/${name}`),
      ),
    ),
  }
}

function generatedOutput() {
  return `// Generated by scripts/generate-operation-cost-identities.mjs.\n// Plans bind to the deployed query implementation and complete migration set.\nexport const OPERATION_COST_IDENTITIES = Object.freeze(${JSON.stringify(operationCostIdentities(), null, 2)})\n`
}
const target = path.join(root, "workers/generated/operation-cost-identities.js")
export function assertOperationCostIdentitiesCurrent() {
  if (readFileSync(target, "utf8").replace(/\r\n/g, "\n") !== generatedOutput()) {
    throw new Error("Operation cost identities are stale; regenerate before release")
  }
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.includes("--check")) assertOperationCostIdentitiesCurrent()
  else writeFileSync(target, generatedOutput(), "utf8")
}
