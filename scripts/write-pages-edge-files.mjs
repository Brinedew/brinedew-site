export function molstarVendorPath(version, file) {
  return `static/vendor/pdbe-molstar-${version}/build/${file}`
}

function headerBlock(pattern, headers, detach = []) {
  const lines = [pattern]
  for (const name of detach) lines.push(`  ! ${name}`)
  for (const [name, value] of Object.entries(headers)) lines.push(`  ${name}: ${value}`)
  return lines.join("\n")
}

export function pagesHeadersFile() {
  return [
    "# Generated by scripts/write-pages-edge-files.mjs. Do not edit.",
    headerBlock("/*", {
      ...PUBLIC_SECURITY_HEADERS,
      "Content-Security-Policy": publicContentSecurityPolicy(),
    }),
    // The GeneGuessr document is reached at geneguessr.brinedew.bio/ through a
    // zone URL rewrite to this path; Pages matches the rewritten path.
    headerBlock(
      "/apps/geneguessr/*",
      { "Content-Security-Policy": publicContentSecurityPolicy({ geneguessrGame: true }) },
      ["Content-Security-Policy"],
    ),
    headerBlock("/static/vendor/*", {
      "Cache-Control": "public, max-age=31536000, immutable",
    }),
    headerBlock("/static/geneguessr/protein-index.json", {
      "Cache-Control": "public, max-age=86400",
    }),
    "",
  ].join("\n\n")
}

