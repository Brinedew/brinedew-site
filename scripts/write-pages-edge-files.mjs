export function pagesRedirectsFile() {
  return (
    [
      "# Generated by scripts/write-pages-edge-files.mjs. Do not edit.",
      ...PAGES_REDIRECTS.map(([from, to, status]) => `${from} ${to} ${status}`),
    ].join("\n") + "\n"
  )
}

async function vendorMolstar(publicRoot) {
  for (const entry of MOLSTAR_VENDOR_FILES) {
    const target = path.join(publicRoot, molstarVendorPath(entry.version, entry.file))
    let bytes = null
    try {
      bytes = await readFile(target)
      if (createHash("sha256").update(bytes).digest("hex") !== entry.sha256) bytes = null
    } catch {
      bytes = null
    }
    if (!bytes) {
      const url = `https://cdn.jsdelivr.net/npm/pdbe-molstar@${entry.version}/build/${entry.file}`
      const response = await fetch(url)
      if (!response.ok) throw new Error(`Mol* vendor download failed: ${url} ${response.status}`)
      bytes = Buffer.from(await response.arrayBuffer())
      const digest = createHash("sha256").update(bytes).digest("hex")
      if (digest !== entry.sha256) {
        throw new Error(`Mol* vendor hash mismatch for ${url}: ${digest}`)
      }
      await mkdir(path.dirname(target), { recursive: true })
      await writeFile(target, bytes)
    }
  }
}

export async function writePagesEdgeFiles({ publicRoot = path.join(root, "public") } = {}) {
  await writeFile(path.join(publicRoot, "_headers"), pagesHeadersFile(), "utf8")
  await writeFile(path.join(publicRoot, "_redirects"), pagesRedirectsFile(), "utf8")
  await vendorMolstar(publicRoot)
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await writePagesEdgeFiles()
  console.log("Wrote public/_headers, public/_redirects and pinned Mol* vendor files")
}
