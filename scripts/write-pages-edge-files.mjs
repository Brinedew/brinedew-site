// Writes the Pages edge files that let brinedew.bio and geneguessr.brinedew.bio
// be served as free, unlimited static requests instead of through a Worker
// (B-834). Runs at the end of `pnpm run build` against ./public.
//
//   public/_headers   security headers + CSP from the one policy owner
//   public/_redirects canonical redirects the edge Worker used to issue
//   public/static/vendor/pdbe-molstar-<v>/build/*  pinned Mol* viewer files,
//                     verified by SHA-256, same-origin for GeneGuessr
//
// Host-specific behaviour Pages cannot express (www -> apex, GeneGuessr "/"
// document) lives in cloudflare/the-only-brinedew-static-edge-policy.json.
import { createHash } from "node:crypto"
import { mkdir, readFile, writeFile } from "node:fs/promises"
import path from "node:path"
import { fileURLToPath } from "node:url"
import {
  PUBLIC_SECURITY_HEADERS,
  publicContentSecurityPolicy,
} from "../workers/lib/the-only-public-document-policy-do-not-duplicate.js"

const root = fileURLToPath(new URL("../", import.meta.url))

